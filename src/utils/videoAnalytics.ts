import { PipelineJob, TranscriptLine } from '../types';

/**
 * Formats a duration in seconds to MM:SS or HH:MM:SS
 */
export function formatTimecode(totalSeconds: number): string {
  if (isNaN(totalSeconds) || totalSeconds < 0) return '00:00';
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = Math.floor(totalSeconds % 60);

  const mm = minutes.toString().padStart(2, '0');
  const ss = seconds.toString().padStart(2, '0');

  if (hours > 0) {
    const hh = hours.toString().padStart(2, '0');
    return `${hh}:${mm}:${ss}`;
  }
  return `${mm}:${ss}`;
}

/**
 * Formats a duration in seconds strictly to HH:MM:SS
 */
export function formatTimecodeDetailed(totalSeconds: number): string {
  if (isNaN(totalSeconds) || totalSeconds < 0) return '00:00:00';
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = Math.floor(totalSeconds % 60);

  const hh = hours.toString().padStart(2, '0');
  const mm = minutes.toString().padStart(2, '0');
  const ss = seconds.toString().padStart(2, '0');

  return `${hh}:${mm}:${ss}`;
}

/**
 * Parses timecode string (MM:SS or HH:MM:SS) into seconds
 */
export function parseTimecode(timeStr: string): number {
  if (!timeStr) return 0;
  const parts = timeStr.trim().split(':').map((p) => parseFloat(p) || 0);
  if (parts.length === 3) {
    return parts[0] * 3600 + parts[1] * 60 + parts[2];
  }
  if (parts.length === 2) {
    return parts[0] * 60 + parts[1];
  }
  if (parts.length === 1) {
    return parts[0];
  }
  return 0;
}

/**
 * Filters transcript lines by search keyword and speaker
 */
export function filterTranscript(
  lines: TranscriptLine[],
  query: string,
  speaker: string
): TranscriptLine[] {
  const normalizedQuery = query.toLowerCase().trim();
  const normalizedSpeaker = speaker.toLowerCase().trim();

  return lines.filter((line) => {
    const matchSpeaker =
      normalizedSpeaker === 'all' ||
      normalizedSpeaker === '' ||
      line.speaker.toLowerCase().includes(normalizedSpeaker);

    const matchQuery =
      !normalizedQuery ||
      line.text.toLowerCase().includes(normalizedQuery) ||
      line.speaker.toLowerCase().includes(normalizedQuery);

    return matchSpeaker && matchQuery;
  });
}

/**
 * Aggregates statistics from current active pipeline jobs
 */
export function calculateActiveJobsStats(jobs: PipelineJob[]) {
  const running = jobs.filter((j) => j.status === 'running').length;
  const queued = jobs.filter((j) => j.status === 'queued').length;
  const completed = jobs.filter((j) => j.status === 'completed').length;
  const avgAccuracy =
    jobs.length > 0
      ? jobs.reduce((acc, j) => acc + (j.sttAccuracy || 0), 0) / jobs.length
      : 99.4;

  return {
    running,
    queued,
    completed,
    total: jobs.length,
    avgAccuracy: Number(avgAccuracy.toFixed(1)),
  };
}

/**
 * Generates an SRT (SubRip Subtitle) string from transcript lines
 */
export function generateSrt(lines: TranscriptLine[]): string {
  return lines
    .map((line, idx) => {
      const start = formatTimecodeDetailed(line.seconds) + ',000';
      const end = formatTimecodeDetailed(line.seconds + 12) + ',000';
      return `${idx + 1}\n${start} --> ${end}\n${line.speaker}: ${line.text}\n`;
    })
    .join('\n');
}

/**
 * Generates a WebVTT formatted string from transcript lines
 */
export function generateVtt(lines: TranscriptLine[]): string {
  const header = 'WEBVTT\n\n';
  const body = lines
    .map((line, idx) => {
      const start = formatTimecodeDetailed(line.seconds) + '.000';
      const end = formatTimecodeDetailed(line.seconds + 12) + '.000';
      return `${idx + 1}\n${start} --> ${end}\n<v ${line.speaker}>${line.text}\n`;
    })
    .join('\n');
  return header + body;
}

/**
 * Formats a clean markdown report from summary data
 */
export function generateSummaryMarkdown(
  title: string,
  summary: string,
  actionItems: string[]
): string {
  return `# ${title}\n\n## Executive Summary\n${summary}\n\n## Action Items\n${actionItems.map((item) => `- [ ] ${item}`).join('\n')}\n\n*Generated by VideoPulse AI Enterprise Studio*\n`;
}
